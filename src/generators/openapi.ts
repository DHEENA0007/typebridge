import {
  SchemaDocument,
  TypeDefinition,
  FieldDefinition,
  TypeNode,
  EnumValue,
} from '../ir/types';

export interface OpenAPIGeneratorOptions {
  title?: string;
  version?: string;
  description?: string;
  mode?: 'openapi' | 'mcp';
  indent?: number;
}

/**
 * Compiles universal SchemaDocument AST into OpenAPI 3.1.0 or Model Context Protocol (MCP) Tool definitions.
 */
export function generateOpenAPI(
  doc: SchemaDocument,
  options: OpenAPIGeneratorOptions = {}
): string {
  const mode = options.mode ?? 'openapi';
  const indent = options.indent ?? 2;

  if (mode === 'mcp') {
    return generateMCPTools(doc, indent);
  }

  const schemas: Record<string, any> = {};

  for (const def of doc.definitions) {
    if (def.kind === 'struct') {
      schemas[def.name] = structToSchema(def);
    } else if (def.kind === 'enum') {
      schemas[def.name] = enumToSchema(def);
    } else if (def.kind === 'alias') {
      schemas[def.name] = {
        description: def.description,
        ...typeNodeToSchema(def.targetType),
      };
    } else if (def.kind === 'union') {
      schemas[def.name] = {
        description: def.description,
        oneOf: def.variants.map((v) => typeNodeToSchema(v)),
      };
    }
  }

  const spec = {
    openapi: '3.1.0',
    info: {
      title: options.title || doc.title || 'TypeBridge API Specification',
      version: options.version || doc.version || '1.0.0',
      description:
        options.description ||
        doc.description ||
        'Cross-language API schema automatically generated by TypeBridge compiler.',
    },
    components: {
      schemas,
    },
  };

  return JSON.stringify(spec, null, indent) + '\n';
}

/**
 * Emits Anthropic / Claude Model Context Protocol (MCP) tool schema definitions.
 */
export function generateMCPTools(doc: SchemaDocument, indent = 2): string {
  const tools: Array<{
    name: string;
    description: string;
    inputSchema: Record<string, any>;
  }> = [];

  for (const def of doc.definitions) {
    if (def.kind === 'struct') {
      const toolName = `create_${toSnakeCase(def.name)}`;
      tools.push({
        name: toolName,
        description:
          def.description || `Submit or validate a ${def.name} structured entity.`,
        inputSchema: structToSchema(def),
      });
    }
  }

  return (
    JSON.stringify(
      {
        $schema: 'https://modelcontextprotocol.io/schema/tools.json',
        tools,
      },
      null,
      indent
    ) + '\n'
  );
}

function structToSchema(def: Extract<TypeDefinition, { kind: 'struct' }>): Record<string, any> {
  const properties: Record<string, any> = {};
  const required: string[] = [];

  for (const field of def.fields) {
    properties[field.name] = {
      description: field.description,
      ...typeNodeToSchema(field.type),
    };
    if (field.defaultValue !== undefined) {
      properties[field.name].default = field.defaultValue;
    }
    if (!field.optional) {
      required.push(field.name);
    }
  }

  const schema: Record<string, any> = {
    type: 'object',
    properties,
    additionalProperties: false,
  };

  if (def.description) {
    schema.description = def.description;
  }
  if (required.length > 0) {
    schema.required = required;
  }

  return schema;
}

function enumToSchema(def: Extract<TypeDefinition, { kind: 'enum' }>): Record<string, any> {
  const values = def.values.map((v) => v.value);
  const isAllString = values.every((v) => typeof v === 'string');

  return {
    type: isAllString ? 'string' : ['string', 'number'],
    enum: values,
    description: def.description,
  };
}

function typeNodeToSchema(node: TypeNode): Record<string, any> {
  switch (node.kind) {
    case 'primitive':
      switch (node.primitive) {
        case 'string':
          return { type: 'string' };
        case 'number':
          return { type: 'number' };
        case 'integer':
          return { type: 'integer' };
        case 'boolean':
          return { type: 'boolean' };
        case 'date':
          return { type: 'string', format: 'date-time' };
        case 'uuid':
          return { type: 'string', format: 'uuid' };
        case 'any':
          return {};
        case 'null':
          return { type: 'null' };
      }

    case 'reference':
      return { $ref: `#/components/schemas/${node.name}` };

    case 'array':
      return {
        type: 'array',
        items: typeNodeToSchema(node.elementType),
      };

    case 'map':
      return {
        type: 'object',
        additionalProperties: typeNodeToSchema(node.valueType),
      };

    case 'optional':
      return typeNodeToSchema(node.innerType);

    case 'union':
      return {
        oneOf: node.types.map((t) => typeNodeToSchema(t)),
      };

    case 'literal':
      return { const: node.value };
  }
}

function toSnakeCase(str: string): string {
  return str
    .replace(/([A-Z])/g, '_$1')
    .toLowerCase()
    .replace(/^_/, '');
}
