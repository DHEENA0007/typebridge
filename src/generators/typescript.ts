import {
  SchemaDocument,
  TypeDefinition,
  TypeNode,
  FieldDefinition,
} from '../ir/types';

export interface TypeScriptGeneratorOptions {
  includeZod?: boolean;
}

/**
 * Generates clean TypeScript interfaces and optional Zod validation schemas.
 */
export function generateTypeScript(
  doc: SchemaDocument,
  options: TypeScriptGeneratorOptions = { includeZod: false }
): string {
  const lines: string[] = ['// Auto-generated by TypeBridge. DO NOT EDIT DIRECTLY.'];

  if (options.includeZod) {
    lines.push("import { z } from 'zod';");
    lines.push('');
  }

  for (const def of doc.definitions) {
    if (def.kind === 'struct') {
      lines.push(generateTSInterface(def));
      lines.push('');
      if (options.includeZod) {
        lines.push(generateZodSchema(def));
        lines.push('');
      }
    } else if (def.kind === 'enum') {
      lines.push(generateTSEnum(def));
      lines.push('');
    } else if (def.kind === 'alias') {
      lines.push(`export type ${def.name} = ${mapTypeToTS(def.targetType)};`);
      lines.push('');
    }
  }

  return lines.join('\n');
}

function generateTSInterface(def: Extract<TypeDefinition, { kind: 'struct' }>): string {
  const lines: string[] = [];
  if (def.description) {
    lines.push(`/**\n * ${def.description}\n */`);
  }
  lines.push(`export interface ${def.name} {`);

  for (const field of def.fields) {
    const tsType = mapTypeToTS(field.type);
    const optMarker = field.optional ? '?' : '';

    if (field.description) {
      lines.push(`  /** ${field.description} */`);
    }
    lines.push(`  ${field.name}${optMarker}: ${tsType};`);
  }

  lines.push('}');
  return lines.join('\n');
}

function generateZodSchema(def: Extract<TypeDefinition, { kind: 'struct' }>): string {
  const lines: string[] = [`export const ${def.name}Schema = z.object({`];

  for (const field of def.fields) {
    let zodType = mapTypeToZod(field.type);
    if (field.optional) {
      zodType = `${zodType}.optional()`;
    }
    lines.push(`  ${field.name}: ${zodType},`);
  }

  lines.push('});');
  lines.push(`export type ${def.name}Type = z.infer<typeof ${def.name}Schema>;`);
  return lines.join('\n');
}

function generateTSEnum(def: Extract<TypeDefinition, { kind: 'enum' }>): string {
  const lines: string[] = [];
  if (def.description) {
    lines.push(`/**\n * ${def.description}\n */`);
  }
  lines.push(`export enum ${def.name} {`);

  for (const val of def.values) {
    const valString = typeof val.value === 'string' ? `"${val.value}"` : val.value;
    lines.push(`  ${val.name} = ${valString},`);
  }

  lines.push('}');
  return lines.join('\n');
}

function mapTypeToTS(node: TypeNode): string {
  switch (node.kind) {
    case 'primitive':
      switch (node.primitive) {
        case 'string':
        case 'uuid':
          return 'string';
        case 'number':
        case 'integer':
          return 'number';
        case 'boolean':
          return 'boolean';
        case 'date':
          return 'Date';
        case 'null':
          return 'null';
        case 'any':
        default:
          return 'any';
      }
    case 'reference':
      return node.name;
    case 'array':
      return `${mapTypeToTS(node.elementType)}[]`;
    case 'map':
      return `Record<${mapTypeToTS(node.keyType)}, ${mapTypeToTS(node.valueType)}>`;
    case 'optional':
      return `${mapTypeToTS(node.innerType)} | undefined`;
    case 'union':
      return node.types.map(mapTypeToTS).join(' | ');
    case 'literal':
      return typeof node.value === 'string' ? `"${node.value}"` : `${node.value}`;
    default:
      return 'any';
  }
}

function mapTypeToZod(node: TypeNode): string {
  switch (node.kind) {
    case 'primitive':
      switch (node.primitive) {
        case 'string':
          return 'z.string()';
        case 'uuid':
          return 'z.string().uuid()';
        case 'number':
          return 'z.number()';
        case 'integer':
          return 'z.number().int()';
        case 'boolean':
          return 'z.boolean()';
        case 'date':
          return 'z.date()';
        case 'null':
          return 'z.null()';
        case 'any':
        default:
          return 'z.any()';
      }
    case 'reference':
      return `z.lazy(() => ${node.name}Schema)`;
    case 'array':
      return `z.array(${mapTypeToZod(node.elementType)})`;
    case 'map':
      return `z.record(${mapTypeToZod(node.keyType)}, ${mapTypeToZod(node.valueType)})`;
    case 'optional':
      return `${mapTypeToZod(node.innerType)}.optional()`;
    case 'union':
      return `z.union([${node.types.map(mapTypeToZod).join(', ')}])`;
    case 'literal':
      return `z.literal(${typeof node.value === 'string' ? `"${node.value}"` : node.value})`;
    default:
      return 'z.any()';
  }
}
