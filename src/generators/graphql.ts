import {
  SchemaDocument,
  TypeDefinition,
  FieldDefinition,
  TypeNode,
  EnumValue,
} from '../ir/types';

export interface GraphQLGeneratorOptions {
  includeDescriptions?: boolean;
  customScalars?: string[];
  emitInputTypes?: boolean;
}

/**
 * Compiles universal SchemaDocument AST into idiomatic GraphQL Schema Definition Language (SDL).
 */
export function generateGraphQL(
  doc: SchemaDocument,
  options: GraphQLGeneratorOptions = {}
): string {
  const includeDescriptions = options.includeDescriptions ?? true;
  const emitInputTypes = options.emitInputTypes ?? false;
  const lines: string[] = [];

  lines.push('"""');
  lines.push(' * GraphQL Schema generated by TypeBridge Universal Compiler');
  if (doc.title) {
    lines.push(` * Source: ${doc.title}`);
  }
  lines.push(' * https://github.com/DHEENA0007/typebridge');
  lines.push('"""');
  lines.push('');

  // Default custom scalars if needed
  const hasDate = containsPrimitive(doc, 'date');
  const hasUuid = containsPrimitive(doc, 'uuid');
  const hasAny = containsPrimitive(doc, 'any');

  if (hasDate) lines.push('scalar DateTime');
  if (hasUuid) lines.push('scalar UUID');
  if (hasAny) lines.push('scalar JSON');
  if (hasDate || hasUuid || hasAny) lines.push('');

  for (const def of doc.definitions) {
    if (def.kind === 'struct') {
      lines.push(generateGraphQLType(def, includeDescriptions, 'type'));
      lines.push('');

      if (emitInputTypes) {
        lines.push(generateGraphQLType(def, includeDescriptions, 'input'));
        lines.push('');
      }
    } else if (def.kind === 'enum') {
      lines.push(generateGraphQLEnum(def, includeDescriptions));
      lines.push('');
    } else if (def.kind === 'union') {
      lines.push(generateGraphQLUnion(def, includeDescriptions));
      lines.push('');
    }
  }

  return lines.join('\n').trim() + '\n';
}

function generateGraphQLType(
  def: Extract<TypeDefinition, { kind: 'struct' }>,
  includeDesc: boolean,
  kind: 'type' | 'input'
): string {
  const lines: string[] = [];
  const typeName = kind === 'input' ? `${def.name}Input` : def.name;

  if (includeDesc && def.description) {
    lines.push(`"""${def.description}"""`);
  }

  lines.push(`${kind} ${typeName} {`);

  for (const field of def.fields) {
    if (includeDesc && field.description) {
      lines.push(`  """${field.description}"""`);
    }

    const fieldType = mapTypeToGraphQL(field.type, field.name, kind === 'input');
    // In GraphQL SDL: ! means non-nullable (required). Optional fields lack !
    const formattedType = field.optional ? fieldType : `${fieldType}!`;
    lines.push(`  ${field.name}: ${formattedType}`);
  }

  lines.push('}');
  return lines.join('\n');
}

function generateGraphQLEnum(
  def: Extract<TypeDefinition, { kind: 'enum' }>,
  includeDesc: boolean
): string {
  const lines: string[] = [];

  if (includeDesc && def.description) {
    lines.push(`"""${def.description}"""`);
  }

  lines.push(`enum ${def.name} {`);
  for (const val of def.values) {
    if (includeDesc && val.description) {
      lines.push(`  """${val.description}"""`);
    }
    // GraphQL enum values must be valid identifiers, typically UPPERCASE
    const enumVal = val.name.toUpperCase().replace(/[^A-Z0-9_]/g, '_');
    lines.push(`  ${enumVal}`);
  }
  lines.push('}');

  return lines.join('\n');
}

function generateGraphQLUnion(
  def: Extract<TypeDefinition, { kind: 'union' }>,
  includeDesc: boolean
): string {
  const lines: string[] = [];

  if (includeDesc && def.description) {
    lines.push(`"""${def.description}"""`);
  }

  const memberTypes = def.variants
    .map((v) => (v.kind === 'reference' ? v.name : null))
    .filter(Boolean);

  if (memberTypes.length > 0) {
    lines.push(`union ${def.name} = ${memberTypes.join(' | ')}`);
  }

  return lines.join('\n');
}

function mapTypeToGraphQL(node: TypeNode, fieldName: string, isInput = false): string {
  switch (node.kind) {
    case 'primitive':
      switch (node.primitive) {
        case 'string':
          if (/^(id|_id|[a-zA-Z0-9_]+Id)$/i.test(fieldName)) return 'ID';
          return 'String';
        case 'number':
          return 'Float';
        case 'integer':
          return 'Int';
        case 'boolean':
          return 'Boolean';
        case 'date':
          return 'DateTime';
        case 'uuid':
          return 'UUID';
        case 'any':
          return 'JSON';
        default:
          return 'String';
      }

    case 'reference':
      return isInput ? `${node.name}Input` : node.name;

    case 'array':
      // Non-null elements inside list: [Item!]
      const inner = mapTypeToGraphQL(node.elementType, fieldName, isInput);
      return `[${inner}!]`;

    case 'optional':
      return mapTypeToGraphQL(node.innerType, fieldName, isInput);

    case 'map':
      return 'JSON';

    case 'literal':
      return typeof node.value === 'number'
        ? Number.isInteger(node.value)
          ? 'Int'
          : 'Float'
        : typeof node.value === 'boolean'
        ? 'Boolean'
        : 'String';

    default:
      return 'String';
  }
}

function containsPrimitive(doc: SchemaDocument, kind: string): boolean {
  for (const def of doc.definitions) {
    if (def.kind === 'struct') {
      for (const f of def.fields) {
        if (checkNodeForPrimitive(f.type, kind)) return true;
      }
    }
  }
  return false;
}

function checkNodeForPrimitive(node: TypeNode, kind: string): boolean {
  if (node.kind === 'primitive' && node.primitive === kind) return true;
  if (node.kind === 'array') return checkNodeForPrimitive(node.elementType, kind);
  if (node.kind === 'optional') return checkNodeForPrimitive(node.innerType, kind);
  return false;
}
